"""Report writers for the config auditor: Markdown, self-contained HTML, JSON."""
from __future__ import annotations

import html
import json
import os

SEV_COLOR = {"critical": "#8e1b1b", "high": "#c0392b", "medium": "#d68910", "low": "#2874a6", "info": "#5d6d7e"}
STATUS_COLOR = {"pass": "#1e8449", "fail": "#c0392b", "error": "#7d3c98"}


def write_all(res: dict, out_dir: str, device: str = "") -> list[str]:
    os.makedirs(out_dir, exist_ok=True)
    paths = []
    p = os.path.join(out_dir, "audit.json")
    with open(p, "w", encoding="utf-8") as f:
        json.dump(res, f, indent=2)
    paths.append(p)
    for name, text in (("audit.md", markdown(res, device)), ("audit.html", html_report(res, device))):
        p = os.path.join(out_dir, name)
        with open(p, "w", encoding="utf-8") as f:
            f.write(text)
        paths.append(p)
    return paths


def _grade(score: int) -> str:
    return "A" if score >= 90 else "B" if score >= 75 else "C" if score >= 60 else "D" if score >= 40 else "F"


def markdown(res: dict, device: str = "") -> str:
    s = res["summary"]
    L = [f"# Config audit — {device or 'device'}", "",
         f"- Rule pack: **{res['pack']}** (dialect: {res['dialect']}"
         + ("" if res["verified"] else ", **syntax not verified for this dialect**") + ")",
         f"- Score: **{res['score']}/100** (grade {_grade(res['score'])})",
         f"- Checks: {s['checks']} — passed {s['passed']}, failed {s['failed']}, errors {s['errors']}",
         "- Failures by severity: " + (", ".join(f"**{v} {k}**" for k, v in s["by_severity"].items()) or "none"),
         "", "## Failures", ""]
    fails = [f for f in res["findings"] if f["status"] == "fail"]
    if not fails:
        L.append("No failures — all applicable checks passed. ✔")
    for f in fails:
        scope = f" _(interface {f['scope']})_" if f["scope"] and f["scope"] != "(none)" else ""
        L += [f"### [{f['severity'].upper()}] {f['title']}{scope}",
              f"- Rule: `{f['rule_id']}`",
              f"- Detail: {f['detail']}" if f["detail"] else "",
              f"- Remediation: {f['remediation']}" if f["remediation"] else "",
              f"- Reference: {f['reference']}" if f["reference"] else "", ""]
    errs = [f for f in res["findings"] if f["status"] == "error"]
    if errs:
        L += ["## Rule errors", ""] + [f"- `{f['rule_id']}`: {f['detail']}" for f in errs] + [""]
    L += ["## All checks", "", "| Status | Severity | Rule | Title | Scope |", "|---|---|---|---|---|"]
    for f in res["findings"]:
        L.append(f"| {f['status']} | {f['severity']} | `{f['rule_id']}` | {f['title']} | {f['scope']} |")
    L += ["", "_Generated by netconfig-auditor. A passing audit is not a guarantee of security — "
              "it means the config matches this baseline. Review the rule pack against your own standard._", ""]
    return "\n".join(x for x in L if x is not None)


def html_report(res: dict, device: str = "") -> str:
    e = html.escape
    s = res["summary"]
    warn = "" if res["verified"] else (
        f'<p class="warn">⚠ Rule pack dialect <b>{e(res["dialect"])}</b> is not syntax-verified — '
        "confirm the patterns against your device OS before relying on the result.</p>")
    sevbar = "".join(f'<span class="pill" style="background:{SEV_COLOR.get(k)}">{v} {k}</span>'
                     for k, v in s["by_severity"].items()) or "<span class=ok>No failures</span>"
    rows = "".join(
        f'<tr class="{f["status"]}"><td><span class="st" style="color:{STATUS_COLOR.get(f["status"])}">{e(f["status"])}</span></td>'
        f'<td><span class="pill" style="background:{SEV_COLOR.get(f["severity"], "#888")}">{e(f["severity"])}</span></td>'
        f'<td><code>{e(f["rule_id"])}</code></td>'
        f'<td><b>{e(f["title"])}</b>{"<div class=sc>interface " + e(f["scope"]) + "</div>" if f["scope"] and f["scope"]!="(none)" else ""}'
        f'{"<div class=dt>" + e(f["detail"]) + "</div>" if f["detail"] else ""}'
        f'{"<div class=rm>Fix: " + e(f["remediation"]) + "</div>" if f["remediation"] else ""}'
        f'{"<div class=rf>" + e(f["reference"]) + "</div>" if f["reference"] else ""}</td></tr>'
        for f in res["findings"])
    grade = _grade(res["score"])
    gcolor = {"A": "#1e8449", "B": "#58a618", "C": "#d68910", "D": "#c0392b", "F": "#8e1b1b"}[grade]
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Config audit — {e(device or 'device')}</title><style>
:root{{--bg:#f6f7f9;--fg:#1c2833;--card:#fff;--line:#e3e6ea;--mut:#5d6d7e}}
@media (prefers-color-scheme:dark){{:root{{--bg:#12161b;--fg:#e6e9ed;--card:#1b2128;--line:#2c343d;--mut:#9aa5b1}}}}
body{{margin:0;font:14px/1.45 system-ui,Segoe UI,sans-serif;background:var(--bg);color:var(--fg)}}
main{{max-width:1000px;margin:auto;padding:24px 16px}}h1{{font-size:22px}}
.top{{display:flex;gap:18px;align-items:center;flex-wrap:wrap}}
.score{{width:72px;height:72px;border-radius:50%;display:flex;align-items:center;justify-content:center;font-size:30px;font-weight:700;color:#fff;background:{gcolor}}}
.meta{{color:var(--mut)}}.warn{{background:#fff4e5;color:#7a4f01;border:1px solid #f0c674;border-radius:8px;padding:8px 12px}}
@media (prefers-color-scheme:dark){{.warn{{background:#3a2e12;color:#f0c674;border-color:#6b5415}}}}
table{{border-collapse:collapse;width:100%;background:var(--card);margin-top:14px}}td,th{{border-bottom:1px solid var(--line);padding:7px 9px;text-align:left;vertical-align:top}}
th{{color:var(--mut)}}.pill{{color:#fff;border-radius:10px;padding:1px 8px;font-size:12px;margin-right:4px}}
.st{{font-weight:700;text-transform:uppercase;font-size:12px}}tr.fail{{background:rgba(192,57,43,.06)}}
.sc{{color:var(--mut);font-size:12px}}.dt{{font-size:12px;margin-top:3px}}.rm{{font-size:12px;margin-top:3px;color:#1e6b43}}
.rf{{font-size:11px;color:var(--mut);margin-top:2px}}.ok{{color:#1e8449;font-weight:600}}.wrap{{overflow-x:auto}}
</style></head><body><main>
<h1>Configuration audit — {e(device or 'device')}</h1>
<div class="top"><div class="score">{res['score']}</div>
<div><div><b>Grade {grade}</b> · pack <b>{e(res['pack'])}</b> ({e(res['dialect'])})</div>
<div class="meta">{s['checks']} checks · {s['passed']} passed · {s['failed']} failed · {s['errors']} errors</div>
<div style="margin-top:6px">{sevbar}</div></div></div>
{warn}
<div class=wrap><table><tr><th>Status</th><th>Severity</th><th>Rule</th><th>Finding</th></tr>{rows}</table></div>
<p class="meta" style="margin-top:18px">Generated by netconfig-auditor. A passing audit means the config matches this baseline — not that the device is secure. Review the pack against your own standard.</p>
</main></body></html>"""
